"""Procedurally weaves Bloom's book-cloth textures (tileable plain weave). Re-run to regenerate:
    python3 scripts/gen-textures.py
Outputs public/textures/cloth-day.png and cloth-night.png (provenance stored in the PNG text chunk)."""
import numpy as np
from PIL import Image, PngImagePlugin

SIZE = 384          # tile size in px (rendered at 192 css px for 2x screens); large so threads don't band
THREAD = 4          # px per thread
rng = np.random.default_rng(20261017)

def weave(base_hex: str, amp: float, out: str) -> None:
    base = np.array([int(base_hex[i:i + 2], 16) for i in (1, 3, 5)], dtype=np.float64)
    n = SIZE // THREAD
    warp = rng.normal(0, 1, n)          # per vertical thread shade
    weft = rng.normal(0, 1, n)          # per horizontal thread shade
    y, x = np.mgrid[0:SIZE, 0:SIZE]
    ty, tx = y // THREAD, x // THREAD
    over = (tx + ty) % 2 == 0           # plain weave: warp over weft on the checker
    shade = np.where(over, warp[tx], weft[ty])
    # Rounded thread profile: brighter at the crown of each thread, darker at the gaps.
    py = (y % THREAD + 0.5) / THREAD
    px = (x % THREAD + 0.5) / THREAD
    crown = np.where(over, np.sin(np.pi * px), np.sin(np.pi * py))
    fibre = rng.normal(0, 0.35, (SIZE, SIZE))
    # Per-thread variation stays small: strong values read as plaid stripes once the tile repeats.
    lum = 1 + amp * (0.18 * shade + 0.9 * (crown - 0.64) + fibre)
    img = np.clip(base[None, None, :] * lum[..., None], 0, 255).astype(np.uint8)
    meta = PngImagePlugin.PngInfo()
    meta.add_text("Source", "Procedural plain-weave book-cloth, generated by scripts/gen-textures.py (seed 20261017). No external imagery.")
    Image.fromarray(img, "RGB").save(out, pnginfo=meta, optimize=True)
    print("wrote", out)

weave("#EBC0B3", 0.045, "public/textures/cloth-day.png")
weave("#3E262D", 0.10, "public/textures/cloth-night.png")
